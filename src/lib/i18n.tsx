type Dictionary = (typeof dictionary)["en"];

interface LanguageContextValue {
  lang: Language;
  setLang: (lang: Language) => void;
  t: Dictionary;
  toggle: () => void;
  currentLanguage: LanguageInfo;
  isRTL: boolean;
  isLanguageModalOpen: boolean;
  openLanguageModal: () => void;
  closeLanguageModal: () => void;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>("en");
  const [isLanguageModalOpen, setIsLanguageModalOpen] = useState(false);

  useEffect(() => {
    try {
      const saved = window.localStorage.getItem("ei-lang") as Language | null;
      if (saved) {
        setLangState(saved);
        const info = getLanguageByCode(saved);
        document.documentElement.lang = saved;
        document.documentElement.dir = info.direction || "ltr";
      }
    } catch {
      // Ignore local storage errors
    }
  }, []);

  const setLang = useCallback((next: Language) => {
    setLangState(next);
    const info = getLanguageByCode(next);
    
    try {
      window.localStorage.setItem("ei-lang", next);
      
      // Set cookies for Google Translate integration
      const googleCode = next === "zh-CN" ? "zh-CN" : next === "zh-TW" ? "zh-TW" : next === "or" || next === "od" ? "or" : next;
      document.cookie = `googtrans=/en/${googleCode}; path=/; domain=${window.location.hostname}`;
      document.cookie = `googtrans=/en/${googleCode}; path=/`;
      document.cookie = `googtrans=/auto/${googleCode}; path=/; domain=${window.location.hostname}`;
      document.cookie = `googtrans=/auto/${googleCode}; path=/`;
    } catch {
      // Ignore cookie errors
    }

    document.documentElement.lang = next;
    document.documentElement.dir = info.direction || "ltr";

    // Dispatch custom event for real-time translation listener
    window.dispatchEvent(
      new CustomEvent("explore-india:language-change", {
        detail: { lang: next, languageInfo: info },
      })
    );
  }, []);

  const toggle = useCallback(() => {
    setIsLanguageModalOpen(true);
  }, []);

  const openLanguageModal = useCallback(() => {
    setIsLanguageModalOpen(true);
  }, []);

  const closeLanguageModal = useCallback(() => {
    setIsLanguageModalOpen(false);
  }, []);

  const currentLanguage = useMemo(() => getLanguageByCode(lang), [lang]);
  const isRTL = currentLanguage.direction === "rtl";

  const t = useMemo(() => {
    // Return language dictionary with fallback to English
    const dict = dictionary[lang] || dictionary[lang.split("-")[0]] || dictionary.en;
    return {
      ...dictionary.en,
      ...dict,
      nav: { ...dictionary.en.nav, ...(dict?.nav || {}) },
      home: { ...dictionary.en.home, ...(dict?.home || {}) },
      common: { ...dictionary.en.common, ...(dict?.common || {}) },
    } as Dictionary;
  }, [lang]);

  const value = useMemo(
    () => ({
      lang,
      setLang,
      toggle,
      t,
      currentLanguage,
      isRTL,
      isLanguageModalOpen,
      openLanguageModal,
      closeLanguageModal,
    }),
    [
      lang,
      setLang,
      toggle,
      t,
      currentLanguage,
      isRTL,
      isLanguageModalOpen,
      openLanguageModal,
      closeLanguageModal,
    ]
  );

  return (
    <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx;
}
