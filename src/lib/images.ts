// ============================================
// HELPER FUNCTION: Get image with quality params
// ============================================
export function getImageUrl(
  url: string,
  preset: keyof typeof imageQuality = "card"
): string {
  if (!url) return fallbacks.transparent;

  // If URL already has Unsplash parameters, return as-is
  if (url.includes("auto=format")) return url;

  // Add Unsplash parameters if it's an Unsplash URL
  if (url.includes("unsplash.com")) {
    const { width, quality } = imageQuality[preset];
    return `${url}?auto=format&fit=crop&w=${width}&q=${quality}`;
  }

  return url;
}

// ============================================
// RANDOM FALLBACK IMAGE GENERATOR
// ============================================
export function getRandomFallbackImage(): string {
  const allImages = [
    ...galleryImages.natureScenes,
    ...galleryImages.temples,
    ...galleryImages.cities,
  ];
  return allImages[Math.floor(Math.random() * allImages.length)];
}